#include "Plane.hpp"
#include <glm.hpp>
#include <vector>
#include <iostream>

namespace udit
{

    const GLfloat Plane::coordinates[] =
    {
       -1,-1,+1,            // 0
       +1,-1,+1,            // 1
       +1,+1,+1,            // 2
       -1,+1,+1,            // 3
    };

    const GLfloat Plane::colors[] =
    {
        0, 0, 1,            // 0    RGB-coloured plane
        1, 0, 1,            // 1
        1, 1, 1,            // 2
        0, 1, 1,            // 3
    };

    const GLuint Plane::indices[] =
    {
        0, 1, 2,            // front
        0, 2, 3,
    };

    Plane::Plane()
    {
        // Generate the plane VBO ids:
        glGenBuffers(VBO_COUNT, vbo_ids);
        glGenVertexArrays(1, &vao_id);

        Subdivision(10);

        glBindVertexArray(0);
    }

    Plane::~Plane()
    {
        // Release the VBOs and the VAO:
        glDeleteVertexArrays(1, &vao_id);
        glDeleteBuffers(VBO_COUNT, vbo_ids);
    }

    void Plane::Subdivision(int amount)
    {
        const int vertexCount = amount + 1;

        // Positions (x, y, z) of every vertex generated by the subdivision.
        std::vector<glm::vec3> newCoords;

        // RGB colour of every vertex of the subdivided plane.
        std::vector<glm::vec3> newColors;

        /* Vertex indices of the triangles that make up the subdivided plane.
            - Avoids duplicating vertices shared by several triangles.
            - Lets a single vertex buffer be reused to build every triangle.
        */
        std::vector<GLuint>    newIndices;

        // Generate vertices and colours
        for (int y = 0; y < vertexCount; ++y)
        {
            for (int x = 0; x < vertexCount; ++x)
            {
                float fx = -1.0f + 2.0f * x / amount;
                float fy =  1.0f - 2.0f * y / amount;
                newCoords.emplace_back(fx, fy, 1.0f); // z = 1.0 (XY plane)

                float r = static_cast<float>(x) / amount;
                float g = static_cast<float>(y) / amount;
                newColors.emplace_back(r, g, 1.0f); // gradient
            }
        }

        // Generate indices
        for (int y = 0; y < amount; ++y)
        {
            for (int x = 0; x < amount; ++x)
            {
                int topLeft     = y * vertexCount + x;
                int topRight    = topLeft + 1;
                int bottomLeft  = (y + 1) * vertexCount + x;
                int bottomRight = bottomLeft + 1;

                newIndices.push_back(topLeft    );
                newIndices.push_back(bottomLeft );
                newIndices.push_back(topRight   );

                newIndices.push_back(topRight   );
                newIndices.push_back(bottomLeft );
                newIndices.push_back(bottomRight);
            }
        }

        // Upload the data to the VBOs
        glBindVertexArray(vao_id);

        // Coordinates
        glBindBuffer(GL_ARRAY_BUFFER, vbo_ids[COORDINATES_VBO]);
        glBufferData(GL_ARRAY_BUFFER, newCoords.size() * sizeof(glm::vec3), newCoords.data(), GL_STATIC_DRAW);
        glEnableVertexAttribArray(0);
        glVertexAttribPointer(0, 3, GL_FLOAT, GL_FALSE, 0, nullptr);

        // Colours
        glBindBuffer(GL_ARRAY_BUFFER, vbo_ids[COLORS_VBO]);
        glBufferData(GL_ARRAY_BUFFER, newColors.size() * sizeof(glm::vec3), newColors.data(), GL_STATIC_DRAW);
        glEnableVertexAttribArray(1);
        glVertexAttribPointer(1, 3, GL_FLOAT, GL_FALSE, 0, nullptr);

        // Indices
        glBindBuffer(GL_ELEMENT_ARRAY_BUFFER, vbo_ids[INDICES_EBO]);
        glBufferData(GL_ELEMENT_ARRAY_BUFFER, newIndices.size() * sizeof(GLuint), newIndices.data(), GL_STATIC_DRAW);

        glBindVertexArray(0);

        this->indexCount = static_cast<GLsizei>(newIndices.size());
    }

    void Plane::render()
    {
        // Enable wireframe mode
        glPolygonMode(GL_FRONT_AND_BACK, GL_LINE);
        // Bind the VAO holding the object data and draw its elements:
        glBindVertexArray(vao_id);
        glDrawElements(GL_TRIANGLES, indexCount, GL_UNSIGNED_INT, 0); 
        glBindVertexArray(0);
    }

}
